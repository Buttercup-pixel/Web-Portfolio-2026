(() => {
  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => [...r.querySelectorAll(s)];

  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ---------- Counter-scrolling columns ----------
     Left column drifts up 12% faster than the page, right column 12% slower. */
  const colUp = $('#col-up');
  const colDown = $('#col-down');
  const SPEED = 0.12;
  let ticking = false;

  function applyParallax() {
    ticking = false;
    if (reduced) return;
    const y = window.scrollY || window.pageYOffset || 0;
    colUp.style.transform = `translate3d(0, ${(-y * SPEED).toFixed(2)}px, 0)`;
    colDown.style.transform = `translate3d(0, ${(y * SPEED).toFixed(2)}px, 0)`;
  }
  function requestParallax() {
    if (!ticking) { ticking = true; requestAnimationFrame(applyParallax); }
  }
  window.addEventListener('scroll', requestParallax, { passive: true });
  window.addEventListener('resize', requestParallax);
  applyParallax();

  /* ---------- Entry scroll hints ---------- */
  const hints = $('#hints');
  const hintMakeup = $('#hint-makeup');
  const hintDigital = $('#hint-digital');
  let hintsDone = false;
  let startY = window.scrollY || 0;

  function placeHints() {
    if (hintsDone) return;
    const a = $('#makeup-1').getBoundingClientRect();
    const b = $('#digital-1').getBoundingClientRect();
    const w = Math.max(window.innerWidth, 1);
    hintMakeup.style.left = `${((a.left + a.width / 2) / w) * 100}%`;
    hintDigital.style.left = `${((b.left + b.width / 2) / w) * 100}%`;
  }
  function dismissHints() {
    if (hintsDone) return;
    hintsDone = true;
    hints.classList.add('is-leaving');
    setTimeout(() => hints.classList.add('is-fading'), 360);
    setTimeout(() => { hints.hidden = true; }, 820);
    ['wheel', 'touchmove', 'click', 'keydown'].forEach((t) => window.removeEventListener(t, dismissHints));
    window.removeEventListener('scroll', onScrollHints);
  }
  function onScrollHints() {
    if (Math.abs((window.scrollY || 0) - startY) > 1) dismissHints();
  }
  placeHints();
  window.addEventListener('resize', placeHints, { passive: true });
  window.addEventListener('scroll', onScrollHints, { passive: true });
  ['wheel', 'touchmove', 'click'].forEach((t) => window.addEventListener(t, dismissHints, { passive: true }));

  /* ---------- Cursor labels ---------- */
  const labels = { makeup: $('#cursor-makeup'), digital: $('#cursor-digital') };
  const finePointer = window.matchMedia('(hover: hover) and (pointer: fine)').matches;
  let activeLabel = null;

  function moveLabels(e) {
    const el = activeLabel;
    if (el) el.style.transform = `translate(-50%, -50%) translate(${e.clientX}px, ${e.clientY}px)`;
  }
  function setLabel(cat, e) {
    const next = cat ? labels[cat] : null;
    if (next !== activeLabel) {
      if (activeLabel) activeLabel.classList.remove('is-on');
      activeLabel = next;
      if (next) next.classList.add('is-on');
    }
    if (next && e) moveLabels(e);
  }
  if (finePointer) {
    $$('.item').forEach((item) => {
      item.addEventListener('pointerenter', (e) => setLabel(item.dataset.category, e));
      item.addEventListener('pointermove', (e) => setLabel(item.dataset.category, e));
      item.addEventListener('pointerleave', () => setLabel(null));
    });
    window.addEventListener('scroll', () => { /* keep label attached to pointer position */ }, { passive: true });
  }

  /* ---------- Gallery overlay ----------
     Content comes from gallery-data.js (generated by tools/build-gallery.py). */
  const overlay = $('#overlay');
  const panel = $('#panel');
  const title = $('#gallery-title');
  const infoBtn = $('#info-btn');
  const details = $('#gallery-details');
  const detailsInner = details.querySelector('.gallery__details-inner');
    const stripTrack = $('#strip-track');
  const mainBox = $('#gallery-main');
  const supporting = $('#gallery-supporting');
  const galleries = window.GALLERIES || {};
  let current = null;
  let lastFocus = null;

  const all = Object.values(galleries);
  let order = [];
  let catOrder = [];
  function buildStrip(cat, key) {
    catOrder = all.filter((g) => g.category === cat);
    order = catOrder;
    $('#strip-title').textContent = `other in ${cat}`;
    stripTrack.replaceChildren();
    {
      order.forEach((g) => {
        const b = document.createElement('button');
        b.type = 'button';
        b.className = `strip__thumb${['acte', 'l8', 'mamika'].includes(g.key) ? ' strip__thumb--logo' : ''}`;
        b.dataset.key = g.key;
        if (g.key === key) b.classList.add('is-current');
        b.setAttribute('aria-label', g.hover);
        b.title = g.hover;
        b.append(makeImg(g.thumb, '', true));
        b.addEventListener('click', () => go(g.key));
        stripTrack.append(b);
      });
    }
    sizeStrip();
  }
  function sizeStrip() {
    if (!order.length || !stripTrack.clientWidth) return;
    const gap = 10;
    const vw = stripTrack.clientWidth - 16;
    const n = order.length;
    const size = Math.min(190, Math.max(56, Math.ceil(Math.ceil((vw - 12 - n * gap) / (n - 1)) * 1.1)));
    stripTrack.style.setProperty('--thumb', `${size}px`);
    const cur = stripTrack.querySelector('.is-current');
    stripTrack.scrollLeft = cur ? cur.offsetLeft - (stripTrack.clientWidth - cur.offsetWidth) / 2 : 0;
    syncBar();
  }
  window.addEventListener('resize', () => { if (!overlay.hidden) sizeStrip(); });
  const bar = $('#strip-bar');
  function syncBar() {
    const max = stripTrack.scrollWidth - stripTrack.clientWidth;
    bar.style.left = `${max > 0 ? (stripTrack.scrollLeft / max) * 70 : 0}%`;
  }
  stripTrack.addEventListener('scroll', syncBar, { passive: true });
  // Wheel over the filmstrip, or scrolling further at the bottom of a project,
  // slides the filmstrip sideways.
  panel.addEventListener('wheel', (e) => {
    if (!current || !e.deltaY) return;
    const overStrip = e.target.closest && e.target.closest('#strip');
    const atBottom = panel.scrollTop + panel.clientHeight >= panel.scrollHeight - 2;
    if (!overStrip && !(atBottom && e.deltaY > 0)) return;
    const max = stripTrack.scrollWidth - stripTrack.clientWidth;
    const canMove = e.deltaY > 0 ? stripTrack.scrollLeft < max - 1 : stripTrack.scrollLeft > 0;
    if (!canMove) return;
    e.preventDefault();
    stripTrack.scrollLeft += e.deltaY;
  }, { passive: false });
  function go(key) { openGallery($(`.item[data-gallery="${key}"]`)); }
  function step(dir) {
    if (!current) return;
    const i = catOrder.findIndex((g) => g.key === current.key);
    go(catOrder[(i + dir + catOrder.length) % catOrder.length].key);
  }
  function setInfo(open) {
    // Animate to the content's real height rather than a fixed guess —
    // with an eased curve, a target much taller than the content makes
    // the reveal finish almost instantly instead of over the full
    // transition.
    details.style.maxHeight = open ? `${detailsInner.scrollHeight}px` : '0px';
    details.classList.toggle('is-open', open);
    infoBtn.classList.toggle('is-open', open);
    infoBtn.setAttribute('aria-expanded', String(open));
  }

  function withFallback(img, fb) {
    if (!fb) return;
    img.addEventListener('error', () => { img.src = fb; }, { once: true });
  }
  function makeImg(it, alt, lazy) {
    const img = new Image();
    img.alt = alt;
    img.decoding = 'async';
    if (lazy) img.loading = 'lazy';
    withFallback(img, it.fb);
    img.src = it.src;
    return img;
  }
  function el(tag, cls, text) {
    const n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text) n.textContent = text;
    return n;
  }

  function renderDetails(list) {
    detailsInner.replaceChildren();
    list.forEach((sec) => {
      if (sec.h) detailsInner.append(el('p', 'credit-heading', sec.h));
      if (sec.t) detailsInner.append(el('p', null, sec.t));
      (sec.lines || []).forEach((l) => detailsInner.append(el('p', null, l)));
    });
  }

  function renderMain(d) {
    mainBox.replaceChildren();
    const m = d.main;
    const ratio = m.w / m.h;
    mainBox.classList.toggle('gallery__main--wide', ratio >= 1.15);
    mainBox.style.aspectRatio = `${m.w} / ${m.h}`;
    mainBox.style.setProperty('--w', `${Math.round(ratio >= 1 ? 780 : Math.min(480, 552 * ratio))}px`);
    if (m.video) {
      const v = document.createElement('video');
      v.src = m.video;
      v.poster = m.src;
      v.muted = true; v.loop = true; v.autoplay = true; v.playsInline = true;
      v.setAttribute('aria-label', d.title);
      mainBox.append(v);
      v.play().catch(() => {});
    } else {
      const img = makeImg(m, d.title, false);
      img.id = 'gallery-main-img';
      mainBox.append(img);
    }
  }

  // Landscape/square photos span the full width; portraits sit in pairs;
  // a leftover single portrait is centred; very tall ones stand alone.
  function renderSupporting(d) {
    supporting.replaceChildren();
    const kind = (it) => {
      const r = it.w / it.h;
      if (r >= 1) return 'wide';
      if (r < 0.6) return 'solo';
      return 'half';
    };
    // pairPortraits: never leave a lone portrait; a landscape waits until the
    // pending portrait has found a partner, so landscapes always stand alone.
    let list = d.items;
    if (d.pairPortraits) {
      list = [];
      let pending = null;
      let deferred = [];
      d.items.forEach((it) => {
        if (it.w >= it.h) {
          if (pending) deferred.push(it); else list.push(it);
        } else if (pending) {
          list.push(pending, it, ...deferred);
          pending = null;
          deferred = [];
        } else {
          pending = it;
        }
      });
      if (pending) list.push(pending);
      list.push(...deferred);
    }
    const items = list.map((it) => ({ it, k: kind(it) }));
    const fill = (box, it) => {
      if (it.video) {
        const v = document.createElement('video');
        v.src = it.video;
        v.poster = it.src;
        v.muted = true; v.loop = true; v.autoplay = true; v.playsInline = true;
        v.setAttribute('aria-hidden', 'true');
        box.append(v);
      } else {
        box.append(makeImg(it, '', true));
      }
    };
    for (let i = 0; i < items.length; i++) {
      const { it, k } = items[i];
      let cls = k;
      if (k === 'half') {
        let run = 0;
        for (let j = i; j < items.length && items[j].k === 'half'; j++) run++;
        const pos = (() => { let n = 0; for (let j = i - 1; j >= 0 && items[j].k === 'half'; j--) n++; return n; })();
        if (pos === run - 1 && run % 2 === 1 && pos % 2 === 0) cls = 'solo';
      }
      if (cls === 'half') {
        // A pair shares one row height: each photo is as wide as its own
        // proportions need, so nothing is cropped or stretched.
        const row = el('div', 'photo-row');
        [it, items[i + 1].it].forEach((p) => {
          const box = el('div', 'photo photo--half');
          box.style.aspectRatio = `${p.w} / ${p.h}`;
          box.style.flex = `${p.w / p.h} 1 0`;
          fill(box, p);
          row.append(box);
        });
        supporting.append(row);
        i++;
        continue;
      }
      const box = el('div', `photo photo--${cls}`);
      box.style.aspectRatio = `${it.w} / ${it.h}`;
      box.style.setProperty('--w', `${Math.round(cls === 'wide' ? 780 : Math.min(382, 490 * (it.w / it.h)))}px`);
      fill(box, it);
      supporting.append(box);
    }
  }

  function openGallery(trigger) {
    const key = trigger && trigger.dataset && trigger.dataset.gallery;
    const d = key && galleries[key];
    if (!d) return;
    current = d;
    title.textContent = d.title;
    renderMain(d);
    renderDetails(d.details);
    renderSupporting(d);
    lastFocus = trigger || document.activeElement;
    closeAbout(true);
    setInfo(false);
    overlay.hidden = false;
    panel.scrollTop = 0;
    buildStrip(d.category, d.key);
    setLabel(null);
    panel.focus({ preventScroll: true });
  }
  function closeGallery() {
    if (overlay.hidden) return;
    overlay.hidden = true;
    if (lastFocus && typeof lastFocus.focus === 'function') lastFocus.focus({ preventScroll: true });
  }

  panel.tabIndex = -1;
  panel.style.outline = 'none';

  $$('.item[data-gallery]').forEach((item) => {
    item.addEventListener('click', () => openGallery(item));
    item.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); openGallery(item); }
    });
  });

  $('#overlay-backdrop').addEventListener('click', closeGallery);

  infoBtn.addEventListener('click', (e) => { e.stopPropagation(); setInfo(!details.classList.contains('is-open')); });
  title.addEventListener('click', (e) => { e.stopPropagation(); setInfo(!details.classList.contains('is-open')); });

  // Click anywhere inside the panel that isn't a photo (or the credits
  // accordion) closes it too.
  panel.addEventListener('click', (e) => {
    if (e.target.tagName === 'IMG' || e.target.tagName === 'VIDEO' || e.target.closest('#strip')) return;
    closeGallery();
  });

  /* ---------- About overlay ---------- */
  const about = $('#about');
  const aboutPanel = $('#about-panel');
  const aboutBtn = $('#about-btn');

  function openAbout() {
    closeGallery();
    about.hidden = false;
    aboutBtn.setAttribute('aria-expanded', 'true');
    aboutPanel.scrollTop = 0;
    setLabel(null);
    sizeBoard();
    aboutPanel.focus({ preventScroll: true });
  }
  function closeAbout(silent) {
    if (about.hidden) return;
    about.hidden = true;
    aboutBtn.setAttribute('aria-expanded', 'false');
    if (!silent) aboutBtn.focus({ preventScroll: true });
  }
  aboutBtn.addEventListener('click', () => (about.hidden ? openAbout() : closeAbout()));

  // Tap anywhere in the about panel closes it, except on links or the
  // drawing board (so people can actually use those).
  aboutPanel.addEventListener('click', (e) => {
    if (e.target.closest('a, #trace')) return;
    closeAbout();
  });

  window.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') { closeGallery(); closeAbout(); }
    if (!overlay.hidden && about.hidden) {
      if (e.key === 'ArrowRight') step(1);
      if (e.key === 'ArrowLeft') step(-1);
    }
  });

  /* ---------- "Leave a trace" drawing board ---------- */
  const canvas = $('#trace-canvas');
  const board = $('#trace-board');
  const ctx = canvas.getContext('2d');
  const BOARD_H = 420;
  const STROKE = 'rgb(255, 45, 45)';
  const strokeHistory = [];
  const saved = [];
  let drawing = false;

  function sizeBoard() {
    const w = board.getBoundingClientRect().width;
    if (!w) return;
    const dpr = Math.max(1, window.devicePixelRatio || 1);
    const pw = Math.max(1, Math.floor(w * dpr));
    const ph = Math.max(1, Math.floor(BOARD_H * dpr));
    if (canvas.width !== pw || canvas.height !== ph) { canvas.width = pw; canvas.height = ph; }
    canvas.style.width = `${w}px`;
    canvas.style.height = `${BOARD_H}px`;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';
    ctx.lineWidth = 3;
    ctx.strokeStyle = STROKE;
  }
  function pos(e) {
    const r = canvas.getBoundingClientRect();
    return { x: e.clientX - r.left, y: e.clientY - r.top };
  }
  canvas.addEventListener('pointerdown', (e) => {
    const { x, y } = pos(e);
    strokeHistory.push(canvas.toDataURL('image/png'));
    canvas.setPointerCapture(e.pointerId);
    drawing = true;
    ctx.beginPath();
    ctx.moveTo(x, y);
  });
  canvas.addEventListener('pointermove', (e) => {
    if (!drawing) return;
    const { x, y } = pos(e);
    ctx.lineTo(x, y);
    ctx.stroke();
  });
  const endStroke = (e) => {
    if (!drawing) return;
    drawing = false;
    if (canvas.hasPointerCapture(e.pointerId)) canvas.releasePointerCapture(e.pointerId);
  };
  ['pointerup', 'pointercancel', 'pointerleave'].forEach((t) => canvas.addEventListener(t, endStroke));

  function clearBoard() {
    const r = canvas.getBoundingClientRect();
    ctx.clearRect(0, 0, r.width, BOARD_H);
  }
  function undo() {
    if (!strokeHistory.length) return false;
    const snap = strokeHistory.pop();
    const r = canvas.getBoundingClientRect();
    const img = new Image();
    img.onload = () => { ctx.clearRect(0, 0, r.width, BOARD_H); ctx.drawImage(img, 0, 0, r.width, BOARD_H); };
    img.src = snap;
    return true;
  }
  $('#trace-undo').addEventListener('click', undo);
  $('#trace-clear').addEventListener('click', clearBoard);
  $('#trace-save').addEventListener('click', () => {
    const url = canvas.toDataURL('image/png');
    if (!url) return;
    saved.push(url);
    const img = new Image();
    img.src = url;
    img.alt = `saved drawing ${saved.length}`;
    $('#trace-grid').insertBefore(img, $('#trace-count'));
    $('#trace-count').textContent = `${saved.length} people have left a trace`;
  });
  window.addEventListener('keydown', (e) => {
    if ((e.metaKey || e.ctrlKey) && !e.shiftKey && e.key.toLowerCase() === 'z' && !about.hidden && undo()) e.preventDefault();
  });
  window.addEventListener('resize', () => { if (!about.hidden) sizeBoard(); });

  /* ---------- Go up (page) ---------- */
  $('#page-goup').addEventListener('click', (e) => {
    e.preventDefault();
    window.scrollTo({ top: 0, behavior: reduced ? 'auto' : 'smooth' });
    window.history.replaceState(null, '', location.pathname + location.search);
  });

  /* ---------- Brand name: back to home ---------- */
  $('#brand-btn').addEventListener('click', () => {
    closeGallery();
    closeAbout(true);
    window.scrollTo({ top: 0, behavior: reduced ? 'auto' : 'smooth' });
    window.history.replaceState(null, '', location.pathname + location.search);
  });
})();
